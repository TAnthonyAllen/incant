#!/bin/bash
export INCANT_NOVIEW=1   # SEQ 686: show never opens a viewer from a script of Clod's
#  formFiles.sh -- SEQ 687 (the show dispatch 2g): regenerates incant/formFiles, the fILEs entries for the forms, from the walk in
#  incant/formWalk. Generated, never typed. Entries are sorted by name so a regeneration is byte-stable; a duplicate name fails the
#  script and writes nothing. --check regenerates into a scratch file and diffs it against the committed one (the seal's check).
cd "$(dirname "$0")/.." || exit 1
B="${INCANT:-$HOME/bin/incant}"
T=$(mktemp -d)
perl -e 'alarm 60; exec @ARGV' "$B" incant/formWalk > "$T/o" 2> "$T/e"; x=$?
if [ $x != 0 ] || ! grep -q '^FORMWALK SENTINEL' "$T/e" || ! grep -q '^FORMWALK BAD 0' "$T/e" || grep -q 'REFUSED\|ERROR' "$T/e"; then
    echo "  FAIL  formWalk exit $x"; grep 'REFUSED' "$T/e"; rm -rf "$T"; exit 1; fi
grep "File='" "$T/o" | sed 's/ *$//' > "$T/lines"
dups=$(awk '{print $1}' "$T/lines" | sort | uniq -d)
if [ -n "$dups" ]; then
    for d in $dups; do echo "  FAIL  formWalk -- two files named $d: $(awk -v n="$d" '$1==n{sub(/^File=/,"",$2); printf "%s ", $2}' "$T/lines")"; done
    rm -rf "$T"; exit 1; fi
{
echo "/*  formFiles -- GENERATED by genLadder/formFiles.sh from incant/formWalk (SEQ 687). Do not type here: add a form file to a"
echo "    directory the walk names and rerun the script. The fILEs entries the bootstrap show (incant/setup) looks a form up in.  */"
echo "registry(fILEs);"
echo "define"
sort "$T/lines"
echo "    ;"
} > "$T/formFiles"
if [ "$1" = "--check" ]; then
    if cmp -s "$T/formFiles" incant/formFiles; then echo "  ok    incant/formFiles = a fresh regeneration ($(grep -c "File='" incant/formFiles) entries)"; rm -rf "$T"; exit 0
    else echo "  FAIL  incant/formFiles differs from a fresh regeneration:"; diff incant/formFiles "$T/formFiles"; rm -rf "$T"; exit 1; fi
fi
cp "$T/formFiles" incant/formFiles; echo "  wrote incant/formFiles, $(grep -c "File='" incant/formFiles) entries"; rm -rf "$T"
