#!/bin/bash
export INCANT_NOVIEW=1   # SEQ 686: show never opens a viewer from a script of Clod's
#  stash.sh -- SEQ 688 (the stash dispatch, Tony 2026-11-17): regenerates incant/stash, the sTASh entries, from the hand-kept list
#  incant/stashList by the walk in incant/stashWalk. Generated, never typed. Entries are sorted by name so a regeneration is
#  byte-stable. Errant, each refused by name with nothing written: a listed name with no file, a listed name with two files (both
#  named), a stated directory that cannot be read. --check regenerates into a scratch file and diffs it against the committed one.
cd "$(dirname "$0")/.." || exit 1
B="${INCANT:-$HOME/bin/incant}"
T=$(mktemp -d)
perl -e 'alarm 60; exec @ARGV' "$B" incant/stashWalk > "$T/o" 2> "$T/e"; x=$?
bad=0
if grep -q 'load: could not open' "$T/e"; then
    grep 'load: could not open' "$T/e" | sed 's/.*load: could not open */  REFUSED stash -- a stated directory cannot be read: /'; bad=1; fi
grep '^REFUSED' "$T/e" | sed 's/^/  /'; grep -q '^REFUSED' "$T/e" && bad=1
if [ $x != 0 ] || ! grep -q '^STASHWALK SENTINEL' "$T/e" || ! grep -q '^STASHWALK BAD 0' "$T/e"; then bad=1; fi
if [ $bad != 0 ]; then echo "  FAIL  stashWalk exit $x -- nothing written"; rm -rf "$T"; exit 1; fi
grep "File='" "$T/o" | sed 's/ *$//' | sort > "$T/lines"
{
echo "/*  stash -- GENERATED by genLadder/stash.sh from the hand-kept list incant/stashList (SEQ 688). Do not type here: add a name"
echo "    to incant/stashList and rerun the script. The sTASh entries show (incant/setup) looks a name up in, by qualified name.  */"
echo "registry(sTASh);"
echo "define"
cat "$T/lines"
echo "    ;"
} > "$T/stash"
if [ "$1" = "--check" ]; then
    if cmp -s "$T/stash" incant/stash; then echo "  ok    incant/stash = a fresh regeneration ($(grep -c "File='" incant/stash) entries)"; rm -rf "$T"; exit 0
    else echo "  FAIL  incant/stash differs from a fresh regeneration:"; diff incant/stash "$T/stash"; rm -rf "$T"; exit 1; fi
fi
cp "$T/stash" incant/stash; echo "  wrote incant/stash, $(grep -c "File='" incant/stash) entries"; rm -rf "$T"
